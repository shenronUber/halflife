"""Pack pre-authored transparent HUD paintings as native RGBA sprites, offline."""
import argparse
import hashlib
import json
import math
import shutil
import struct
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import build_cache

ROOT = Path(__file__).resolve().parent
CONFIG = ROOT/'data/headgear_hud.json'
ASSETS = ROOT/'assets/headgear/hud'
OUT = ROOT/'generated/headgear-hud'
HEADER = ROOT.parent/'cl_dll/vf_headgear_hud_catalog.h'

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def native_sprite(path, frame):
    # Same Xash Version-32 format as status decals, with a rectangular frame.
    # True alpha preserves the clear opening and translucent glass edge.
    width, height = frame.size
    header = struct.pack('<4siifiiifi', b'IDSP', 32, 2, math.hypot(width,height)/2,
                         width, height, 1, 0., 0)
    path.write_bytes(header+struct.pack('<iiiii',0,-width//2,height//2,width,height)+frame.tobytes())

def build(ensure=False):
    config = json.loads(CONFIG.read_text(encoding='utf-8'))
    entries = config['assets']; size = tuple(config['size'])
    assert [e['type'] for e in entries] == [1,2,3,4,5] and size == (1024,576)
    inputs = [Path(__file__),Path(build_cache.__file__),CONFIG]+[ASSETS/'sources'/e['source'] for e in entries]
    fingerprint = build_cache.fingerprint(inputs)
    manifest = OUT/'manifest.json'
    if ensure and build_cache.current(build_cache.read(manifest).get('cache'),fingerprint):
        print('Current authored headgear HUD: 5 transparent textures / native RGBA sprites');return
    OUT.mkdir(parents=True,exist_ok=True);(ASSETS/'frames').mkdir(parents=True,exist_ok=True)
    outputs=[];reports=[]
    header=['// Generated by vector-fields/build_headgear_hud.py.','#ifndef VF_HEADGEAR_HUD_CATALOG_H',
            '#define VF_HEADGEAR_HUD_CATALOG_H','namespace vfhud {','struct Asset {int type;const char* id;};',
            'static const Asset assets[]={']
    gallery=Image.new('RGB',(1280,5*400),'#17212a');draw=ImageDraw.Draw(gallery)
    font=ImageFont.truetype('C:/Windows/Fonts/segoeui.ttf',21)
    for i,entry in enumerate(entries):
        source=ASSETS/'sources'/entry['source'];painting=Image.open(source)
        assert painting.mode=='RGBA', (source,painting.mode)
        assert abs(painting.width/painting.height-16/9)<.06,source
        assert painting.getchannel('A').getextrema()==(0,255),source
        # Format conversion only; never paint a replacement frame or fill its opening.
        frame=painting.resize(size,Image.Resampling.LANCZOS)
        alpha=frame.getchannel('A');w,h=size
        center=alpha.crop((round(w*.45),round(h*.45),round(w*.55),round(h*.55)))
        assert center.getextrema()[1]<=8, (source,'Aim center must remain clear')
        frame_path=ASSETS/'frames'/(entry['id']+'.png');frame.save(frame_path);outputs.append(frame_path)
        sprite=OUT/(entry['id']+'.spr');native_sprite(sprite,frame);outputs.append(sprite)
        header.append('{%d,"%s"},'%(entry['type'],entry['id']))
        # Preview uses two backgrounds solely to expose the retained alpha.
        for col,bg in enumerate(('#17232c','#aab4b8')):
            panel=Image.new('RGBA',(640,360),bg);panel.alpha_composite(frame.resize(panel.size,Image.Resampling.LANCZOS))
            gallery.paste(panel.convert('RGB'),(col*640,i*400+36))
        draw.text((10,i*400+6),entry['name'],font=font,fill='#e1e9e8')
        reports.append(dict(type=entry['type'],id=entry['id'],source=entry['source'],source_size=painting.size,
            source_sha256=sha(source),sprite_sha256=sha(sprite),frame_sha256=sha(frame_path),
            center_alpha_max=center.getextrema()[1],clear_fraction=sum(v<=8 for v in alpha.getdata())/(w*h)))
    header+=['};','enum {Count=5,Width=1024,Height=576};','}','#endif']
    HEADER.write_text('\n'.join(header)+'\n',encoding='utf-8');outputs.append(HEADER)
    preview=ASSETS/'contact-sheet.jpg';gallery.save(preview,quality=94);outputs.append(preview)
    manifest.write_text(json.dumps(dict(version=1,size=size,assets=reports,
        blend='native RGBA; authored transparent openings; no generated-at-runtime geometry',
        cache=build_cache.record(fingerprint,outputs)),indent=2)+'\n',encoding='utf-8')
    print('PASS headgear HUD: 5 authored paintings, 5 native RGBA sprites, clear aim centers')

def runtime_files():
    manifest=OUT/'manifest.json'
    data=json.loads(manifest.read_text(encoding='utf-8'))
    result=[(manifest,Path('vf/headgear-hud.json'))]
    for entry in data['assets']:
        source=OUT/(entry['id']+'.spr')
        assert sha(source)==entry['sprite_sha256'],source
        result.append((source,Path('sprites/vf_headgear_hud')/source.name))
    return result

def deploy(mod):
    for source,target in runtime_files():
        target=Path(mod)/target;target.parent.mkdir(parents=True,exist_ok=True)
        if target.exists() and sha(source)==sha(target):continue
        # A test may have inherited an immutable hardlink; detach before copying.
        if target.is_file() and target.stat().st_nlink>1:target.unlink()
        shutil.copy2(source,target)

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--ensure',action='store_true');build(parser.parse_args().ensure)
